func testPool(t *testing.T) *pgxpool.Pool {
	t.Helper()
	dsn := os.Getenv("PRODUCT_TEST_DATABASE_URL")
	if dsn == "" {
		t.Skip("set PRODUCT_TEST_DATABASE_URL to run PostgreSQL integration test")
	}
	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()
	config, err := pgxpool.ParseConfig(dsn)
	if err != nil {
		t.Fatal(err)
	}
	// Keep the temporary table on one connection; persistent tables are untouched.
	config.MaxConns = 1
	pool, err := pgxpool.NewWithConfig(ctx, config)
	if err != nil {
		t.Fatal(err)
	}
	t.Cleanup(pool.Close)
	_, err = pool.Exec(ctx, `CREATE TEMP TABLE products (
		id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
		owner_id BIGINT NOT NULL, sku VARCHAR(64) NOT NULL UNIQUE, name VARCHAR(200) NOT NULL,
		price BIGINT NOT NULL CHECK (price >= 0), stock BIGINT NOT NULL CHECK (stock >= 0),
		created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
		updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP, deleted_at TIMESTAMPTZ
	)`)
	if err != nil {
		t.Fatal(err)
	}
	return pool
}

func TestFindAllPostgres(t *testing.T) {
	pool := testPool(t)
	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()
	repository := repo.NewGetRepo(pool)
	products, err := repository.FindAll(ctx)
	if err != nil || len(products) != 0 {
		t.Fatalf("empty catalog: products=%v, err=%v", products, err)
	}
	created := time.Date(2026, 1, 2, 3, 4, 5, 123000000, time.UTC)
	updated := created.Add(time.Hour)
	_, err = pool.Exec(ctx, `INSERT INTO products VALUES
		(8, 7, 'SKU-8', '商品8', 1980, 0, $1, $2, NULL),
		(2, 7, 'SKU-2', '削除済み', 100, 5, $1, $2, $2),
		(1, 9, 'SKU-1', '商品1', 2980, 30, $1, $2, NULL)`, created, updated)
	if err != nil {
		t.Fatal(err)
	}
	products, err = repository.FindAll(ctx)
	if err != nil {
		t.Fatal(err)
	}
	if len(products) != 2 || products[0].ID() != 1 || products[1].ID() != 8 {
		t.Fatalf("expected active products ordered by ID: %v", products)
	}
	product := products[0]
	if product.OwnerID() != 9 || product.Sku() != "SKU-1" || product.Name() != "商品1" ||
		product.Price() != 2980 || product.Stock() != 30 ||
		!product.CreatedAt().Equal(created) || !product.UpdatedAt().Equal(updated) {
		t.Fatalf("unexpected product fields: %+v", product)
	}
	if products[1].Stock() != 0 {
		t.Fatal("out-of-stock products must be included")
	}
}

func TestProductMutationsPostgres(t *testing.T) {
	pool := testPool(t)
	ctx, cancel := context.WithTimeout(context.Background(), 10*time.Second)
	defer cancel()
	r := repo.NewGetRepo(pool)
	input := domain.ProductInput{SKU: "SKU-1", Name: "商品", Price: 1000, Stock: 5}
	product, err := r.Create(ctx, 7, input)
	if err != nil {
		t.Fatal(err)
	}
	id := product.ID()
	if id <= 0 || product.OwnerID() != 7 || product.Sku() != input.SKU || product.Name() != input.Name ||
		product.Price() != 1000 || product.Stock() != 5 || product.CreatedAt().IsZero() || product.UpdatedAt().IsZero() {
		t.Fatalf("unexpected created product: %+v", product)
	}
	if _, err := r.Create(ctx, 8, input); !errors.Is(err, domain.ErrSKUAlreadyExists) {
		t.Fatalf("expected duplicate SKU: %v", err)
	}
	second, err := r.Create(ctx, 7, domain.ProductInput{SKU: "SKU-2", Name: "別商品", Price: 1, Stock: 1})
	if err != nil {
		t.Fatal(err)
	}
	if _, err := r.Update(ctx, second.ID(), domain.ProductPatch{SKU: &input.SKU}); !errors.Is(err, domain.ErrSKUAlreadyExists) {
		t.Fatalf("expected duplicate SKU on update: %v", err)
	}
	zero := int64(0)
	patch := domain.ProductPatch{Price: &zero, Stock: &zero}
	updated, err := r.Update(ctx, id, patch)
	if err != nil {
		t.Fatal(err)
	}
	if updated.Price() != 0 || updated.Stock() != 0 || updated.Name() != input.Name || updated.Sku() != input.SKU ||
		!updated.CreatedAt().Equal(product.CreatedAt()) || !updated.UpdatedAt().After(product.UpdatedAt()) {
		t.Fatalf("partial update did not preserve omitted fields: %+v", updated)
	}
	page, err := r.List(ctx, domain.Page{Limit: 1, Offset: 1})
	if err != nil || len(page) != 1 || page[0].ID() != second.ID() {
		t.Fatalf("unexpected page: %v, err=%v", page, err)
	}
	if err := r.Delete(ctx, id); err != nil {
		t.Fatal(err)
	}
	if _, err := r.FindByID(ctx, id); !errors.Is(err, domain.ErrProductNotFound) {
		t.Fatalf("deleted product is still visible: %v", err)
	}
	if _, err := r.Update(ctx, id, patch); !errors.Is(err, domain.ErrProductNotFound) {
		t.Fatalf("deleted product can be updated: %v", err)
	}
	if err := r.Delete(ctx, id); !errors.Is(err, domain.ErrProductNotFound) {
		t.Fatalf("expected NotFound on repeated delete: %v", err)
	}
	products, err := r.FindAll(ctx)
	if err != nil || len(products) != 1 || products[0].ID() != second.ID() {
		t.Fatalf("unexpected active products: %v, err=%v", products, err)
	}
	var deleted bool
	if err := pool.QueryRow(ctx, "SELECT deleted_at IS NOT NULL FROM products WHERE id=$1", id).Scan(&deleted); err != nil || !deleted {
		t.Fatalf("expected logical deletion: deleted=%v, err=%v", deleted, err)
	}
	if _, err := r.Create(ctx, 7, input); !errors.Is(err, domain.ErrSKUAlreadyExists) {
		t.Fatalf("deleted SKU must remain reserved, matching Hono: %v", err)
	}
}
